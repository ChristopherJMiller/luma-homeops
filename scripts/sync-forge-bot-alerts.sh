#!/usr/bin/env bash
# Copy forge-bot's alert rules and their promtool tests out of the forge-bot release that
# cluster/forge-bot/statefulset.yaml pins, into cluster/forge-bot/:
#   prometheusrule.yaml  the PrometheusRule forge-bot-alerts, whose spec is internal/metrics/alerts.yaml
#   alerts_test.yaml     internal/metrics/alerts_test.yaml, byte for byte (not a manifest: the
#                        kustomization does not list it)
# Run it after every re-pin. scripts/test-forge-bot-alerts.sh (pre-commit hook forge-bot-alerts)
# fails while the copy and the pinned commit differ. Never edit the two files by hand: change the
# rules in forge-bot, release, review, re-pin, then sync.
#
#   nix develop --command scripts/sync-forge-bot-alerts.sh
#
# The forge-bot checkout is $FORGE_BOT_SRC (default ~/Repos/forge-bot) and must contain the pinned
# commit (git -C ~/Repos/forge-bot fetch). Read-only there; no network, no cluster.
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
dir=$repo/cluster/forge-bot
src=${FORGE_BOT_SRC:-$HOME/Repos/forge-bot}

# Chris's global git config rewrites URLs and signs in as him; none of it applies here. A git
# hook's GIT_DIR, GIT_INDEX_FILE and friends would point -C back at luma-homeops; drop them.
fgit() {
  env -u GIT_DIR -u GIT_WORK_TREE -u GIT_INDEX_FILE -u GIT_COMMON_DIR -u GIT_OBJECT_DIRECTORY \
    -u GIT_ALTERNATE_OBJECT_DIRECTORIES -u GIT_PREFIX GIT_CONFIG_GLOBAL=/dev/null git -C "$src" "$@"
}

short=$(sed -nE 's#^ *image: git\.realliance\.net/realliance-ops/forge-bot:sha-([0-9a-f]{7})@sha256:[0-9a-f]{64}$#\1#p' "$dir/statefulset.yaml")
[ "$(printf '%s\n' "$short" | grep -c .)" -eq 1 ] || { echo "sync: expected exactly one pinned forge-bot image in $dir/statefulset.yaml" >&2; exit 2; }
full=$(fgit rev-parse --verify --quiet "$short^{commit}") ||
  { echo "sync: commit $short is not in $src; run: git -C $src fetch" >&2; exit 2; }

rules=$(fgit show "$full:internal/metrics/alerts.yaml")
{
  cat <<EOF
---
# GENERATED by scripts/sync-forge-bot-alerts.sh: the spec is internal/metrics/alerts.yaml of
# git.realliance.net/realliance-ops/forge-bot at $full,
# the commit of the pinned image. Do not edit; re-sync after a re-pin.
# scripts/test-forge-bot-alerts.sh lints it, runs forge-bot's promtool tests (alerts_test.yaml)
# and checks it still equals that commit's file.
apiVersion: monitoring.coreos.com/v1
kind: PrometheusRule
metadata:
  name: forge-bot-alerts
  labels:
    prometheus: kube-prometheus
    role: alert-rules
    release: prometheus
spec:
EOF
  # Indent the whole file by two under spec:; blank lines stay empty.
  printf '%s\n' "$rules" | sed -E 's/^(.)/  \1/'
} > "$dir/prometheusrule.yaml"
fgit show "$full:internal/metrics/alerts_test.yaml" > "$dir/alerts_test.yaml"
echo "synced forge-bot alerts from $full"
